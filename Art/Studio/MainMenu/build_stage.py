"""Turn painted_stage.json (Art/MainMenu/menu_export.py) into Luau that builds the painted menu stage in the Main Menu
place (Edit mode), and the two data modules the client reads.

    python -I Art/Studio/MainMenu/build_stage.py [--backdrop E:/Rensei/Renders/MainMenu/upload/backdrop_full.png]
    python -I Art/Tools/rbxc.py luau "placeId: 123967384111466" Edit @E:/Rensei/Work/main-menu/build_stage.lua

Builds Workspace.PaintedStage (persistent streaming, every part anchored and not collidable): the parts (Roblox
materials), the alcove wall with its niches subtracted (SubtractAsync), lamps as lights in invisible anchors, the
decal panels (banners, clock, sign, chalk circles) and the three backdrop tiles, each panel carrying an ImageKey
attribute. It replaces an earlier PaintedStage (the old MenuStage and its forest are left as they are).
Also writes, beside this file: MenuStage.lua (ReplicatedStorage.Modules.Data.Rensei.MenuStage: the markers) and,
only if it doesn't exist yet, MenuArt.lua (ReplicatedStorage.Modules.Data.Rensei.MenuArt: the image and sound ids,
0 until the owner approves the uploads). The Luau also writes both modules into the place.
Needs PIL for the backdrop tiles (run without -I if PIL is only in the user site).
"""
import argparse
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def lua(v, indent=""):
	"""A JSON-ish value as a Luau literal."""
	if isinstance(v, dict):
		inner = ", ".join(f"{k} = {lua(x)}" if k.isidentifier() else f'["{k}"] = {lua(x)}' for k, x in v.items())
		return "{" + inner + "}"
	if isinstance(v, (list, tuple)):
		return "{" + ", ".join(lua(x) for x in v) + "}"
	if isinstance(v, bool):
		return "true" if v else "false"
	if isinstance(v, str):
		return json.dumps(v)
	if v is None:
		return "nil"
	return repr(round(v, 4)) if isinstance(v, float) else str(v)


def light_props(l):
	"""Blender watts -> a Roblox light's Range (studs) and Brightness (a rough match by eye)."""
	w = max(l["watts"], 0.1)
	if l["kind"] == "SPOT":
		return min(60, 6 + math.sqrt(w) * 0.55), min(6, 0.6 + math.log10(w) * 0.9)
	if l["kind"] == "AREA":
		return 16, 0.6
	return max(5, min(40, math.sqrt(w) * 1.25)), max(0.8, min(4, 0.5 + math.log10(w) * 0.8))


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--json", default=os.path.join(HERE, "painted_stage.json"))
	ap.add_argument("--backdrop", default="E:/Rensei/Renders/MainMenu/upload/backdrop_full.png")
	ap.add_argument("--out", default="E:/Rensei/Work/main-menu/build_stage.lua")
	a = ap.parse_args()
	d = json.load(open(a.json))
	mk = d["markers"]
	mats_path = os.path.join(os.path.dirname(a.backdrop), "materials.json")  # menu_bake.py's tile sizes
	mats = json.load(open(mats_path)) if os.path.exists(mats_path) else {}

	# the backdrop's three tiles (Roblox images are at most 1024 px a side)
	try:
		from PIL import Image
		im = Image.open(a.backdrop).convert("RGB")
		for t in range(3):
			im.crop((t * 1024, 0, (t + 1) * 1024, 1024)).save(os.path.join(os.path.dirname(a.backdrop), f"backdrop_{t + 1}.png"))
		print("tiles written beside", a.backdrop)
	except ImportError:
		print("PIL missing: backdrop tiles not cut")

	stage_mod = "-- The painted menu stage's markers (generated by Art/Studio/MainMenu/build_stage.py from Art/MainMenu/menu_export.py).\n" \
		"-- Positions are world studs in the Main Menu place; cameras are {pos, look, fov (vertical, degrees)}.\n" \
		"return " + lua(mk) + "\n"
	open(os.path.join(HERE, "MenuStage.lua"), "w", encoding="utf-8").write(stage_mod)
	art_path = os.path.join(HERE, "MenuArt.lua")
	if not os.path.exists(art_path):
		open(art_path, "w", encoding="utf-8").write(
			"-- The painted menu's uploaded art and sound (rbxassetid numbers). 0 = not uploaded yet: the menu then falls back\n"
			"-- to the UI kit's frames, and panels with no image stay hidden. The owner approves every upload first.\n"
			"return {\n"
			"\tBackdrop = {0, 0, 0}, -- E:/Rensei/Renders/MainMenu/upload/backdrop_1..3.png, left to right\n"
			"\tbanner = 0, clock = 0, sign = 0, chalk_circle = 0, -- the decal panels' ImageKey attributes\n"
			"\tCardFrame = 0, CardFrameHover = 0, ButtonFrame = 0, -- 9-slice: 60 px margins on the 860 x 150 / 700 x 76 art\n"
			"\t-- the baked materials (MaterialVariants Rensei<Key>): E:/Rensei/Renders/MainMenu/upload/mat_<Key>_<map>.png\n"
			"\tMaterials = {\n"
			+ "".join(f"\t\t{k} = {{color = 0, normal = 0, roughness = 0, metalness = 0}},\n" for k in ("WallStone", "Flagstones", "StatueStone", "Iron", "RustIron"))
			+ "\t},\n"
			"\tAmbience = 0, -- the 60 s loop (menu_ambience.py --loop)\n"
			"}\n")
	art_mod = open(art_path, encoding="utf-8").read()

	L = []
	w = L.append
	w("-- Generated by Art/Studio/MainMenu/build_stage.py. Builds Workspace.PaintedStage (Edit mode).")
	w('local RS = game:GetService("ReplicatedStorage")')
	w('local old = workspace:FindFirstChild("PaintedStage") if old then old:Destroy() end')
	w('local Stage = Instance.new("Model") Stage.Name = "PaintedStage"')
	w('pcall(function() Stage.ModelStreamingMode = Enum.ModelStreamingMode.Persistent end)')
	w('local Groups = {}')
	w('local function group(name) if name == "" then return Stage end local g = Groups[name] if not g then g = Instance.new("Model") g.Name = name g.Parent = Stage Groups[name] = g end return g end')
	w('local SHAPES = {[0] = Enum.PartType.Block, [1] = Enum.PartType.Cylinder, [2] = Enum.PartType.Ball}')
	w('local function part(r)')
	w('\tlocal p = Instance.new("Part")')
	w('\tp.Name, p.Shape = r[1], SHAPES[r[2]]')
	w('\tlocal base, variant = string.match(r[3], "^(%a+):?(%w*)$")')
	w('\tp.Material = Enum.Material[base] p.Color = Color3.fromHex(r[4])')
	w('\tif variant ~= "" then p.MaterialVariant = variant end')
	w('\tp.Size = Vector3.new(math.max(r[5], 0.05), math.max(r[6], 0.05), math.max(r[7], 0.05))')
	w('\tp.CFrame = CFrame.new(r[8], r[9], r[10], r[11], r[12], r[13], r[14])')
	w('\tp.Anchored, p.CanCollide, p.CanTouch, p.CanQuery = true, false, false, false')
	w('\tp.TopSurface, p.BottomSurface = Enum.SurfaceType.Smooth, Enum.SurfaceType.Smooth')
	w('\treturn p')
	w('end')
	w('local count = 0')
	walls = [p for p in d["parts"] if len(p) > 15]
	plain = [p for p in d["parts"] if len(p) <= 15]
	w("local ROWS = {")
	for p in plain:
		w("\t" + lua(p) + ",")
	w("}")
	w("for i, r in ipairs(ROWS) do")
	w("\tpart(r).Parent = group(r[15])")
	w("\tcount += 1")
	w("\tif i % 150 == 0 then task.wait() end")
	w("end")
	for p in walls:
		w("do -- the alcove wall: its niches subtracted")
		w("\tlocal wall = part(" + lua(p[:15]) + ")")
		w("\tlocal cutters = {}")
		w("\tfor _, c in ipairs(" + lua(p[15]) + ") do")
		w('\t\tlocal q = part({"Cut", c[1], "SmoothPlastic", "ffffff", c[2], c[3], c[4], c[5], c[6], c[7], c[8], c[9], c[10], c[11], ""})')
		w("\t\tq.Parent = workspace table.insert(cutters, q)")
		w("\tend")
		w("\twall.Parent = workspace -- (CSG needs the parts in the DataModel)")
		w("\tlocal ok, u = pcall(function() return wall:SubtractAsync(cutters, Enum.CollisionFidelity.Box, Enum.RenderFidelity.Precise) end)")
		w("\tif ok and u then u.Name = wall.Name u.UsePartColor = true u.Anchored, u.CanCollide, u.CanTouch, u.CanQuery = true, false, false, false u.Parent = Stage wall:Destroy() count += 1")
		w('\telse warn("PaintedStage: the wall subtraction failed: " .. tostring(u)) wall.Parent = Stage end')
		w("\tfor _, q in ipairs(cutters) do q:Destroy() end")
		w("end")
	w("local LIGHTS = {")
	for l in d["lights"]:
		rng, br = light_props(l)
		w("\t" + lua({"name": l["name"], "kind": l["kind"], "pos": l["pos"], "dir": l["dir"], "colour": l["colour"], "angle": l["angle"],
			"shadows": l["shadows"], "group": l["group"], "range": round(rng, 2), "brightness": round(br, 2)}) + ",")
	w("}")
	w("for _, l in ipairs(LIGHTS) do")
	w('\tlocal a = Instance.new("Part") a.Name = "Light_" .. l.name a.Size = Vector3.new(0.2, 0.2, 0.2) a.Transparency = 1')
	w("\ta.Anchored, a.CanCollide, a.CanTouch, a.CanQuery = true, false, false, false")
	w("\tlocal pos, dir = Vector3.new(table.unpack(l.pos)), Vector3.new(table.unpack(l.dir))")
	w("\ta.CFrame = CFrame.lookAt(pos, pos + dir)")
	w('\tlocal li = Instance.new(l.kind == "SPOT" and "SpotLight" or "PointLight")')
	w("\tli.Color = Color3.fromHex(l.colour) li.Range = l.range li.Brightness = l.brightness li.Shadows = l.shadows")
	w('\tif l.kind == "SPOT" then li.Angle = math.min(l.angle, 180) li.Face = Enum.NormalId.Front end')
	w("\tli.Parent = a")
	w('\ta:SetAttribute("Watts", 0) a:SetAttribute("BaseBrightness", l.brightness)')
	w("\ta.Parent = group(l.group)")
	w("end")
	w("local function panel(name, key, pos, normal, up, wdt, hgt, parent)")
	w('\tlocal p = Instance.new("Part") p.Name = name p.Transparency = 1')
	w("\tp.Size = Vector3.new(wdt, hgt, 0.05)")
	w("\tp.Anchored, p.CanCollide, p.CanTouch, p.CanQuery = true, false, false, false")
	w("\tp.CFrame = CFrame.lookAt(pos, pos + normal, up)")
	w('\tlocal dc = Instance.new("Decal") dc.Name = "Image" dc.Face = Enum.NormalId.Front dc.Parent = p')
	w('\tp:SetAttribute("ImageKey", key)')
	w("\tp.Parent = parent")
	w("\treturn p")
	w("end")
	w('local Panels = Instance.new("Folder") Panels.Name = "Panels" Panels.Parent = Stage')
	w("local DECALS = {")
	for dc in d["decals"]:
		w("\t" + lua(dc) + ",")
	w("}")
	w("for _, dc in ipairs(DECALS) do")
	w("\tpanel(dc.name, dc.image, Vector3.new(table.unpack(dc.pos)), Vector3.new(table.unpack(dc.normal)), Vector3.new(table.unpack(dc.up)), dc.w, dc.h, Panels)")
	w("end")
	b = mk["backdrop"]
	w("do -- the painted backdrop: three tiles side by side, facing the menu camera")
	w(f"\tlocal c, n, up = Vector3.new({lua(b['centre'])[1:-1]}), Vector3.new({lua(b['normal'])[1:-1]}), Vector3.new({lua(b['up'])[1:-1]})")
	w(f"\tlocal cf = CFrame.lookAt(c, c + n, up)")
	w(f"\tlocal tw = {b['w']} / 3")
	w("\tfor t = 1, 3 do")
	w("\t\t-- (the panel faces the camera, so its RightVector runs right-to-left as the camera sees it: tile 1 goes on the +Right side)")
	w(f"\t\tlocal pos = (cf * CFrame.new((2 - t) * tw, 0, 0)).Position")
	w(f'\t\tlocal p = panel("Backdrop" .. t, "Backdrop" .. t, pos, n, up, tw + 0.05, {b["h"]}, Stage)')
	w("\tend")
	w("end")
	w('local focus = Instance.new("Part") focus.Name = "Focus" focus.Transparency = 1 focus.Size = Vector3.new(1, 1, 1)')
	w("focus.Anchored, focus.CanCollide, focus.CanTouch, focus.CanQuery = true, false, false, false")
	w(f"focus.Position = Vector3.new({lua(mk['menu_camera']['look'])[1:-1]})")
	w("focus.Parent = Stage")
	w('Stage.PrimaryPart = focus')
	w("Stage.Parent = workspace")
	# the data modules
	w('local Data = RS:WaitForChild("Modules"):WaitForChild("Data"):WaitForChild("Rensei")')
	w("local function module(name, src)")
	w('\tlocal m = Data:FindFirstChild(name) or Instance.new("ModuleScript")')
	w('\tm.Name = name m.Parent = Data')
	w('\tgame:GetService("ScriptEditorService"):UpdateSourceAsync(m, function() return src end)')
	w("end")
	for name, src in (("MenuStage", stage_mod), ("MenuArt", art_mod)):
		lvl = "===="
		while f"]{lvl}]" in src:
			lvl += "="
		w(f"module({json.dumps(name)}, [{lvl}[\n{src}]{lvl}])")
	w("-- the baked materials (menu_bake.py) as MaterialVariants, their maps from MenuArt.Materials once uploaded")
	w('local MS = game:GetService("MaterialService")')
	w('local ArtNow = require(Data.MenuArt)')
	w("for key, def in pairs(" + lua({k: {"base": v["base"], "studs": v["studs_per_tile"]} for k, v in mats.items()}) + ") do")
	w('\tlocal mv = MS:FindFirstChild("Rensei" .. key) or Instance.new("MaterialVariant")')
	w('\tmv.Name = "Rensei" .. key mv.BaseMaterial = Enum.Material[def.base] mv.StudsPerTile = def.studs')
	w("\tlocal ids = ArtNow.Materials and ArtNow.Materials[key] or {}")
	w('\tfor kind, prop in pairs({color = "ColorMap", normal = "NormalMap", roughness = "RoughnessMap", metalness = "MetalnessMap"}) do')
	w('\t\tif ids[kind] and ids[kind] ~= 0 then mv[prop] = "rbxassetid://" .. ids[kind] end')
	w("\tend")
	w("\tmv.Parent = MS")
	w("end")
	w("-- the images already uploaded (MenuArt): onto the panels")
	w("local Art = require(Data.MenuArt)")
	w("for _, p in ipairs(Stage:GetDescendants()) do")
	w('\tlocal key = p:IsA("BasePart") and p:GetAttribute("ImageKey")')
	w("\tif key then")
	w('\t\tlocal id = key:match("^Backdrop(%d)$") and Art.Backdrop[tonumber(key:match("%d"))] or Art[key]')
	w('\t\tif id and id ~= 0 then p.Image.Texture = "rbxassetid://" .. id end')
	w("\tend")
	w("end")
	w('return ("PaintedStage: %d parts, %d lights, %d panels, + 3 backdrop tiles"):format(count, #LIGHTS, #DECALS)')
	open(a.out, "w", encoding="utf-8").write("\n".join(L) + "\n")
	print("wrote", a.out, os.path.getsize(a.out), "bytes;", len(plain), "parts,", len(walls), "csg walls")


if __name__ == "__main__":
	main()
