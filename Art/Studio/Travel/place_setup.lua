-- World Plan 1 Task 4 (2026-10-20): copy Ye's place settings to a region place.
-- Run in Edit mode on Ye. It returns Lua source as one string. Run that source, in Edit mode,
-- in the target place (e.g. Foundry Yard) to apply the settings. The applied chunk returns a summary.
-- Lighting.Technology can't be read or set from the plugin sandbox: the owner sets it by hand.
local out = {"-- generated by Art/Studio/Travel/place_setup.lua from Ye", "local n, bad = 0, {}"}

local function lit(v)
	local t = typeof(v)
	if t == "Color3" then return ("Color3.new(%.6g,%.6g,%.6g)"):format(v.R, v.G, v.B) end
	if t == "EnumItem" then return tostring(v) end
	if t == "string" then return ("%q"):format(v) end
	if t == "number" then return ("%.9g"):format(v) end
	if t == "boolean" then return tostring(v) end
	if t == "Vector3" then return ("Vector3.new(%.9g,%.9g,%.9g)"):format(v.X, v.Y, v.Z) end
	return nil
end

local function prop(inst, path, names)
	for _, name in ipairs(names) do
		local ok, v = pcall(function() return inst[name] end)
		local s = ok and lit(v)
		if s then
			table.insert(out, ("do local ok, e = pcall(function() %s.%s = %s end) if ok then n += 1 else table.insert(bad, %q) end end")
				:format(path, name, s, path .. "." .. name))
		end
	end
end

-- StarterPlayer
prop(game.StarterPlayer, "game.StarterPlayer", {
	"CharacterWalkSpeed", "CharacterJumpPower", "CharacterJumpHeight", "CharacterUseJumpPower",
	"CameraMaxZoomDistance", "CameraMinZoomDistance", "DevComputerMovementMode", "DevTouchMovementMode",
	"DevComputerCameraMovementMode", "LoadCharacterAppearance", "AutoJumpEnabled", "CharacterMaxSlopeAngle",
})

-- Workspace (StreamingEnabled is always on in the region places)
prop(workspace, "workspace", {"Gravity", "FallenPartsDestroyHeight"})
table.insert(out, "pcall(function() workspace.StreamingEnabled = true end)")

-- Lighting
prop(game.Lighting, "game.Lighting", {
	"Brightness", "ClockTime", "Ambient", "OutdoorAmbient", "EnvironmentDiffuseScale", "EnvironmentSpecularScale",
	"GeographicLatitude", "GlobalShadows", "ShadowSoftness", "ExposureCompensation", "ColorShift_Top",
	"ColorShift_Bottom", "FogColor", "FogStart", "FogEnd",
})

-- Lighting children: Atmosphere, Sky, ColorCorrection, Bloom. A clone can't cross places, so each is
-- rebuilt in the target from Ye's property values (found by class, created if missing).
local effects = {
	Atmosphere = {"Density", "Offset", "Color", "Decay", "Glare", "Haze"},
	Sky = {"SkyboxBk", "SkyboxDn", "SkyboxFt", "SkyboxLf", "SkyboxRt", "SkyboxUp", "SunTextureId", "MoonTextureId",
		"SunAngularSize", "MoonAngularSize", "StarCount", "CelestialBodiesShown"},
	ColorCorrectionEffect = {"Enabled", "Brightness", "Contrast", "Saturation", "TintColor"},
	BloomEffect = {"Enabled", "Intensity", "Size", "Threshold"},
}
for _, cls in ipairs({"Atmosphere", "Sky", "ColorCorrectionEffect", "BloomEffect"}) do
	local src = game.Lighting:FindFirstChildOfClass(cls)
	if src then
		-- one local per effect, so prop() can address it by a plain name
		table.insert(out, ('local fx_%s = game.Lighting:FindFirstChildOfClass("%s") or Instance.new("%s")'):format(cls, cls, cls))
		table.insert(out, ('fx_%s.Name = %q fx_%s.Parent = game.Lighting'):format(cls, src.Name, cls))
		prop(src, "fx_" .. cls, effects[cls])
	end
end

-- SoundService
prop(game:GetService("SoundService"), 'game:GetService("SoundService")', {"AmbientReverb", "DistanceFactor", "DopplerScale", "RolloffScale"})

table.insert(out, 'return ("applied %d settings; failed: %s"):format(n, #bad > 0 and table.concat(bad, ", ") or "none")')
return table.concat(out, "\n")
