"""Bundles the forge kit into the reversible Studio script (Foundry data plan, Task 7).

python -I Art/Studio/Regions/Foundry/forge/bundle_forge.py <out.lua> [plan|apply|undo|check|test]
    Fills build_forge.lua.tmpl with forge_kit.json as a Lua table literal (KIT), writes the generated header and the
    MODE line asked for (default "plan") into <out.lua>, and also (re)writes the committed build_forge.lua next to
    this file with MODE = "plan". The output depends only on the kit and the template (the header's date is the
    kit's export date), so a fresh bundle of the same inputs is byte-identical.

To run another MODE in Studio, bundle to the scratch folder with that MODE (or copy the committed file there and edit
only its MODE line). Never regenerate to undo: the kit is what was exported, and undo reads only what apply marked.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT_PATH = os.path.join(HERE, "forge_kit.json")
TMPL_PATH = os.path.join(HERE, "build_forge.lua.tmpl")
OUT_PATH = os.path.join(HERE, "build_forge.lua")
TOOL = "Art/Studio/Regions/Foundry/forge/bundle_forge.py"
MODES = ("plan", "apply", "undo", "check", "test")
MODE_RE = re.compile(r'^local MODE = "[a-z]+"(.*)$', re.M)
HEADER_MARK = "--[[HEADER]]"
KIT_MARK = "--[[KIT]]"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil",
            "not", "or", "repeat", "return", "then", "true", "until", "while", "continue"}


def lua_str(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 32 or o == 127:
            out.append("\\%03d" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def lua_key(k):
    if not isinstance(k, str):
        raise ValueError("a non-string key: %r" % (k,))
    return k if IDENT.match(k) and k not in KEYWORDS else "[" + lua_str(k) + "]"


def lua(v):
    """One value as a Lua literal (one line)."""
    if v is None:
        return "nil"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v != v or v in (float("inf"), float("-inf")):
            raise ValueError("not a finite number")
        return repr(v)
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, list):
        return "{" + ", ".join(lua(x) for x in v) + "}"
    if isinstance(v, dict):
        return "{" + ", ".join(lua_key(k) + " = " + lua(x) for k, x in v.items()) + "}"
    raise ValueError("cannot write a %s" % type(v).__name__)


def kit_literal(kit):
    """The kit as a Lua table literal: one piece / Models entry per line."""
    lines = ["{"]
    for k, v in kit.items():
        if isinstance(v, list):
            lines.append("\t%s = {" % lua_key(k))
            for x in v:
                lines.append("\t\t%s," % lua(x))
            lines.append("\t},")
        else:
            lines.append("\t%s = %s," % (lua_key(k), lua(v)))
    lines.append("}")
    return "\n".join(lines)


def load_kit():
    with open(KIT_PATH, encoding="utf-8") as f:
        return json.load(f)


def load_template():
    with open(TMPL_PATH, encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n")


def kit_date(kit):
    m = re.search(r"(\d{4}-\d{2}-\d{2})", kit.get("Source", ""))
    if not m:
        raise ValueError("the kit's Source has no date")
    return m.group(1)


def generate(mode, kit=None, template=None):
    if mode not in MODES:
        raise ValueError("unknown MODE %r (one of %s)" % (mode, ", ".join(MODES)))
    kit = load_kit() if kit is None else kit
    t = load_template() if template is None else template
    if t.count(HEADER_MARK) != 1 or t.count(KIT_MARK) != 1:
        raise ValueError("the template needs exactly one %s and one %s" % (HEADER_MARK, KIT_MARK))
    if len(MODE_RE.findall(t)) != 1:
        raise ValueError("the template needs exactly one MODE line")
    header = "-- generated by %s from forge_kit.json and build_forge.lua.tmpl (%s): do not edit by hand." % (TOOL, kit_date(kit))
    t = t.replace(HEADER_MARK, header)
    t = MODE_RE.sub(lambda m: 'local MODE = "%s"%s' % (mode, m.group(1)), t)
    t = t.replace(KIT_MARK, kit_literal(kit))
    if "\r" in t:
        raise ValueError("a CR in the bundle")
    return t


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main(argv):
    if len(argv) < 2 or len(argv) > 3:
        print(__doc__)
        return 2
    mode = argv[2] if len(argv) == 3 else "plan"
    if mode not in MODES:
        print("REFUSED: unknown MODE %r (one of %s)" % (mode, ", ".join(MODES)))
        return 2
    out = os.path.abspath(argv[1])
    if os.path.normcase(out) == os.path.normcase(OUT_PATH) and mode != "plan":
        print("REFUSED: the committed build_forge.lua keeps MODE plan; bundle another MODE to the scratch folder")
        return 2
    body = generate(mode)
    write(out, body)
    write(OUT_PATH, generate("plan"))
    print("wrote %s (MODE %s, %d chars) and %s (MODE plan)" % (out, mode, len(body), OUT_PATH))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
